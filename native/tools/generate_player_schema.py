"""Regenerate the checked-in C++ catalog from existing recovered reference schemas.

Only this development utility needs Python 3.14. The executable embeds its result.
"""
import hashlib
import json
import os
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
if sys.version_info[:2] != (3, 14):
    raise SystemExit("Schema regeneration requires the reference CPython 3.14 modules.")
os.environ["ER_ROOT"] = str(root / "runtime/ErCore")
sys.path.insert(0, str(root / "runtime/vendor_pyc"))
import playerstate_protocol
import repdec4

schemas = {}
for profile in ("current", "legacy", "character"):
    if profile == "character":
        cat = repdec4.load_catalogs()["BP_DFMCharacter_C"]
        parents = {p["index"]: p for p in cat["parents"]}
        meta = {p["index"]: p for p in repdec4.load_propmeta()["BP_DFMCharacter_C"]}
    else:
        cat, parents, meta = playerstate_protocol._schema(profile)
    commands = []
    for c in cat["cmds"]:
        parent = parents[c["parent_index"]]
        m = dict(meta.get(c["index"], {}))
        m.setdefault("name", parent["name"])
        commands.append({
            "index": c["index"], "type": c["type"], "end": c.get("end_cmd", 0),
            "name": parent["name"], "single": parent["cmd_end"] - parent["cmd_start"] == 1,
            "meta": {k: v for k, v in m.items() if v is not None and k in (
                "name", "prop_class", "struct", "enum_max", "departure_name",
                "departure_bits", "departure_values")},
        })
    schemas[profile] = commands
text = json.dumps(schemas, ensure_ascii=True, separators=(",", ":"))
out = root / "native/src/player_schema.hpp"
out.write_text('// Generated by native/tools/generate_player_schema.py; do not edit by hand.\n'
               '// Catalog SHA256: ' + hashlib.sha256(text.encode()).hexdigest() + '\n'
               '#pragma once\nnamespace radaer::ue {\n'
               'inline constexpr const char player_schema[] = R"RADAER_SCHEMA('
               + text + ')RADAER_SCHEMA";\n}\n', encoding="utf-8")
print(out)
