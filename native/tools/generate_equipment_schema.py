"""Embed recovered component layouts and original item names; development only."""
import json, os, sys
from pathlib import Path
root=Path(__file__).resolve().parents[2]
os.environ['ER_ROOT']=str(root/'runtime/ErCore')
sys.path.insert(0,str(root/'runtime/vendor_pyc'))
import repdec4
cats=repdec4.load_catalogs(); metas=repdec4.load_propmeta(); layouts={}
for name in ('SOLCharacterEquipComponent','WeaponReplicateComponent','GPAttributeSetHealth'):
    cat=cats[name]; parents={p['index']:p for p in cat['parents']}; meta={m['index']:m for m in metas.get(name,[])}
    layouts[name]=[dict(index=c['index'],type=c['type'],end=c['end_cmd'],name=parents[c['parent_index']]['name'],
        meta={k:v for k,v in meta.get(c['index'],{}).items() if k in ('struct','prop_class','enum_max')}) for c in cat['cmds']]
catalog=json.loads((root/'runtime/ErCore/item_names_cn.json').read_text(encoding='utf-8'))
gear={str(g['id']):{k:g[k] for k in ('name','type','tier')} for g in catalog['gear_catalog'] if g.get('type') in ('头盔','护甲','防弹衣')}
data=json.dumps(dict(layouts=layouts,weapons=catalog['weapon_names'],gear=gear),ensure_ascii=True,separators=(',',':'))
(root/'native/src/equipment_schema.hpp').write_text('// Generated by generate_equipment_schema.py.\n#pragma once\nnamespace radaer {\ninline constexpr const char equipment_schema[]=R"EQUIP('+data+')EQUIP";\n}\n',encoding='utf-8')
print(len(gear),'gear entries;',len(catalog['weapon_names']),'weapon names')
