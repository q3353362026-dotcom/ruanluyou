"""Import the supplied item directory and recovered pickup layout (development only)."""
import json, sys
from pathlib import Path
root = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1])
data = json.loads(source.read_text(encoding='utf-8-sig'))
groups = {'gun':'枪械','ammo':'弹药','acc':'配件','protect':'防具与背具','props':'道具','assets':'外观','vehicle':'载具','dagger':'近战武器','opProps':'干员道具','exchange':'兑换物品','skin':'皮肤'}
items, categories = {}, {}
for key, v in data['items'].items():
    if not key.isdecimal() or not isinstance(v.get('name'), str):
        raise ValueError('Invalid item entry: '+key)
    pc, sc = v.get('pc','').strip(), v.get('sc','').strip()
    category = pc+'/'+sc
    label = v.get('scCN','').strip() or groups.get(pc,'其他')
    group=groups.get(pc,'其他')
    if sc=='collection':
        label=v.get('detail',{}).get('type','').strip() or '其他收集品'
        category+='/'+label;group='收集品'
    categories[category] = dict(name=label, group=group)
    items[key] = dict(name=v['name'], grade=v.get('grade',0), category=category)
out = dict(source=source.name, count=len(items), categories=categories, items=items)
(root/'native/webui/radar/items.json').write_text(json.dumps(out,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
s = json.loads((root/'runtime/ErCore/src/core/pickup_schema_0904.json').read_text(encoding='utf-8'))
parents={p['index']:p for p in s['parents']}; meta={m['index']:m for m in s['meta']}
cmds=[dict(index=c['index'],type=c['type'],end=c['end_cmd'],name=parents[c['parent_index']]['name'],
           single=parents[c['parent_index']]['cmd_end']-parents[c['parent_index']]['cmd_start']==1,
           meta=meta.get(c['index'],{})) for c in s['cmds']]
encoded=json.dumps(cmds,ensure_ascii=True,separators=(',',':'))
(root/'native/src/loot_schema.hpp').write_text('// Generated by generate_loot_catalog.py.\n#pragma once\nnamespace radaer { inline constexpr const char loot_schema[]=R"LOOT('+encoded+')LOOT"; }\n',encoding='utf-8')
print(f'{len(items)} items, {len(categories)} categories, {len(cmds)} pickup commands')
