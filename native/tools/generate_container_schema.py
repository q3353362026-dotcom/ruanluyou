"""Import recovered death-box RepLayouts; no runtime bytecode is executed."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
schemas = {}
for profile, filename in [('death_box', 'death_box_schema_0904.json'),
                          ('death_box_legacy', 'death_box_schema_legacy.json')]:
    source = json.loads((root / 'runtime/ErCore/src/core' / filename).read_text(encoding='utf-8'))
    schema = source['classes']['BP_Inventory_DeadBody_C']
    parents = {p['index']: p for p in schema['parents']}
    metadata = {m['index']: m for m in schema['meta']}
    commands = []
    for c in schema['cmds']:
        p = parents[c['parent_index']]
        m = metadata.get(c['index'], {})
        meta = {k: m[k] for k in ('name', 'prop_class', 'struct', 'enum_max') if k in m}
        # Preserve qualified flattened struct fields without confusing the killer with the deceased.
        path = m.get('field_path', [])
        if len(path) > 1:
            meta['field_name'] = '.'.join(path)
        commands.append(dict(index=c['index'], type=c['type'], end=c['end_cmd'],
                             name=p['name'], single=p['cmd_end'] - p['cmd_start'] == 1, meta=meta))
    schemas[profile] = commands
encoded = json.dumps(schemas, ensure_ascii=True, separators=(',', ':'))
(root / 'native/src/container_schema.hpp').write_text(
    '// Generated by generate_container_schema.py from recovered class-specific RepLayouts.\n'
    '#pragma once\nnamespace radaer { inline constexpr const char container_schema[]=R"BOX('
    + encoded + ')BOX"; }\n', encoding='utf-8')
print({key: len(value) for key, value in schemas.items()})
